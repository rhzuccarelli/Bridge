#!/usr/bin/env python3
"""Generate the checked-in ASCII bitmap fonts used by the firmware UI."""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont


def raster(width: int, height: int, font_size: int) -> list[int]:
    """Rasterize directly onto the target grid; never resize a bitmap glyph."""
    font = ImageFont.load_default(size=font_size)
    output: list[int] = []
    for codepoint in range(32, 127):
        image = Image.new("1", (width, height), 0)
        ImageDraw.Draw(image).text((0, -1), chr(codepoint), font=font, fill=1)
        for y in range(height):
            row = 0
            for x in range(width):
                if image.getpixel((x, y)):
                    row |= 1 << (15 - x)
            output.extend(((row >> 8) & 0xFF, row & 0xFF) if width > 8 else ((row >> 8) & 0xFF,))
    return output


def emit(name: str, values: list[int]) -> str:
    rows = []
    for offset in range(0, len(values), 16):
        rows.append("    " + ", ".join(f"0x{value:02X}" for value in values[offset:offset + 16]))
    return f"constexpr std::array<std::uint8_t, {len(values)}> {name}{{{{\n" + ",\n".join(rows) + "\n}};\n"


root = Path(__file__).resolve().parents[1]
target = root / "src/display/GeneratedFonts.inc"
target.write_text(
    "// Generated by scripts/generate-fonts.py. Do not hand-edit.\n"
    + emit("kSmallGlyphs", raster(8, 12, 10))
    + emit("kLargeGlyphs", raster(12, 16, 14)),
    encoding="utf-8",
)
